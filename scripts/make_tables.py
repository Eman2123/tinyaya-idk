"""Build the final report tables (markdown) from outputs/results/.

  python scripts/make_tables.py            # prints and writes outputs/results/tables.md
Tables: (1) per-language adapters, mean +- std over seeds; (2) paired bootstrap between recipes;
(3) cross-lingual transfer (seed 1, adapter trained on row language, tested on column language);
(4) label quality (probe vs consistency) if outputs/results/label_quality.csv exists.
"""
import os, re, sys
from glob import glob

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))
from common import load_config, out_path, read_jsonl          # noqa: E402
from stats import paired_bootstrap                            # noqa: E402

LANGS = ["en", "es", "ar", "ms"]
METRICS = [("coverage", "coverage"), ("selective_acc", "sel. acc"), ("hallucination_rate", "halluc."),
           ("over_refusal", "over-refusal"), ("abstain_recall", "abstain recall")]
PAIRS = [("R4", "R2"), ("R4", "R3"), ("R4", "R1"), ("R3", "R2"), ("R5", "R4")]


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def load(cfg):
    fr = [pd.read_csv(f) for f in glob(str(out_path(cfg, "results", "eval_*.csv")))]
    df = pd.concat(fr, ignore_index=True)
    p = df["model"].str.extract(r"^(R\d)(?:_([a-z]+))?(?:_s(\d+))?$")
    df["recipe"], df["train"], df["seed"] = p[0], p[1], p[2].astype(float)
    return df


def pm(x):
    x = pd.Series(x).dropna()
    if len(x) == 0:
        return "-"
    if len(x) == 1:
        return f"{x.iloc[0]:.3f}"
    return f"{x.mean():.3f} ± {x.std(ddof=1):.3f}"


def table_main(df):
    rows = []
    for lang in LANGS:
        for rec in sorted(df["recipe"].unique()):
            sub = df[(df["lang"] == lang) & ((df["recipe"] == "R0") if rec == "R0" else
                                              ((df["recipe"] == rec) & (df["train"] == lang)))]
            if sub.empty:
                continue
            row = {"lang": lang, "recipe": rec, "seeds": 1 if rec == "R0" else sub["seed"].nunique()}
            for k, name in METRICS:
                row[name] = pm(sub[k]) if k in sub else "-"
            rows.append(row)
    return pd.DataFrame(rows)


def table_bootstrap(cfg, seeds=(1, 2, 3)):
    rows = []
    for a, b in PAIRS:
        for lang in LANGS:
            per = {}
            for rec in (a, b):
                by = {}
                for sd in seeds:
                    f = out_path(cfg, "results", f"preds_{rec}_{lang}_s{sd}_{lang}.jsonl")
                    if f.exists():
                        for r in read_jsonl(f):
                            by.setdefault(r["id"], []).append(r)
                per[rec] = by
            ids = sorted(set(per[a]) & set(per[b]))
            if not ids:
                continue
            ns = min(min(len(per[a][i]) for i in ids), min(len(per[b][i]) for i in ids))
            row = {"pair": f"{a} - {b}", "lang": lang, "seeds": ns}
            for name, fn in (("halluc.", lambda r: (not r["refused"]) and (not r["correct"])),
                             ("correct", lambda r: r["correct"])):
                x = [np.mean([fn(r) for r in per[a][i][:ns]]) for i in ids]
                y = [np.mean([fn(r) for r in per[b][i][:ns]]) for i in ids]
                d, (lo, hi) = paired_bootstrap(x, y)
                row[name + " diff [95% CI]"] = f"{d:+.3f} [{lo:+.3f}, {hi:+.3f}]" + ("" if lo <= 0 <= hi else " *")
            rows.append(row)
    return pd.DataFrame(rows)


def table_transfer(df, recipe, metric):
    s = df[(df["recipe"] == recipe) & (df["seed"] == 1)]
    if s.empty:
        return None
    m = s.pivot_table(index="train", columns="lang", values=metric, aggfunc="mean")
    m = m.reindex(index=[l for l in LANGS if l in m.index], columns=[l for l in LANGS if l in m.columns]).round(3)
    m.insert(0, "trained on \\ tested on", m.index)
    return m.reset_index(drop=True).fillna("-")


def main():
    cfg = load_config()
    df = load(cfg)
    out = ["# Results tables (auto-generated by scripts/make_tables.py)\n",
           "## 1. Per-language adapters (trained and tested on the same language), mean ± std over seeds\n",
           "Test split, 252 questions per language. halluc. = answered and wrong, over all questions. R0 = base model.\n",
           md(table_main(df)), "\n## 2. Paired bootstrap (questions resampled, outcomes averaged over seeds); * = 95% CI excludes 0\n"]
    tb = table_bootstrap(cfg)
    out.append(md(tb) if not tb.empty else "_no paired predictions yet_")
    for rec in ("R2", "R3", "R4", "R5"):
        for metric in ("hallucination_rate", "selective_acc"):
            t = table_transfer(df, rec, metric)
            if t is not None:
                out += [f"\n## 3. Transfer, {rec}, {metric} (seed 1; rows = training language)\n", md(t)]
    lq = out_path(cfg, "results", "label_quality.csv")
    if lq.exists():
        out += ["\n## 4. Label quality (test split)\n", md(pd.read_csv(lq).round(3))]
    text = "\n".join(out)
    p = out_path(cfg, "results", "tables.md")
    p.write_text(text, encoding="utf-8")
    print(text)
    print("\nwrote", p)


if __name__ == "__main__":
    main()
